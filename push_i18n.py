def normalize_lang(lang):
    l = (lang or "en").replace("_", "-")
    for code in LANGS:
        if l.lower() == code.lower():
            return code
    base = l.split("-")[0].lower()
    if base == "zh":
        return "zh-Hant" if ("hant" in l.lower() or l.lower().endswith(("-tw", "-hk"))) and "zh-Hant" in T else "zh-Hans"
    alias = {"pt": "pt-BR", "sr": "sr-Latn", "no": "nb", "nn": "nb", "iw": "he", "in": "id"}
    if alias.get(base) in T:
        return alias[base]
    return base if base in T else "en"


